package co.xenastudios.neoskript.harness.scenario;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Locale;
import java.util.stream.Stream;

/**
 * The real-world corpus in {@code test-harness/corpus/real-world}. Each {@code <name>.sk} defines a
 * {@code selftest_<name>()} function (with {@code -} as {@code _}), and the generated {@code /corpustest}
 * command runs them all and reports each one as {@code [corpus] <name>: ok} or one line per failure.
 */
final class CorpusRunner {

    static final String COMMAND = "corpustest";

    private CorpusRunner() {}

    /** The corpus scripts, sorted by name. */
    static List<Path> scripts(Path dir) throws IOException {
        try (Stream<Path> files = Files.list(dir)) {
            return files.filter(path -> path.getFileName().toString().endsWith(".sk")).sorted().toList();
        }
    }

    static String suiteName(Path script) {
        String file = script.getFileName().toString();
        return file.substring(0, file.length() - ".sk".length());
    }

    static String selftestFunction(String suite) {
        return "selftest_" + suite.replace('-', '_').toLowerCase(Locale.ROOT);
    }

    static String generate(List<String> suites) {
        StringBuilder script = new StringBuilder()
                .append("# Generated by the NeoSkript test harness. Do not edit.\n")
                .append("command /").append(COMMAND).append(":\n")
                .append("\texecutable by: console\n")
                .append("\ttrigger:\n")
                .append("\t\tdelete {corpus::failures::*}\n");
        for (String suite : suites) {
            script.append("\t\t").append(selftestFunction(suite)).append("()\n");
            script.append("\t\tcorpus_report(\"").append(suite).append("\")\n");
        }
        return script.append("\t\tsend \"[corpus] done\" to console\n").toString();
    }
}
