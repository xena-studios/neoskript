package co.xenastudios.neoskript.harness.scenario;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Generates a deterministic set of realistic scripts for load and reload benchmarks: functions with
 * loops and branches, event handlers using global list variables, commands, and options.
 */
final class BenchmarkScripts {

    static final int FILES = 40;
    static final int FUNCTIONS_PER_FILE = 6;
    static final int EVENTS_PER_FILE = 3;
    static final int COMMANDS_PER_FILE = 2;

    private static final String HEADER = """
            # Generated by the NeoSkript test harness for load benchmarks. Do not edit.
            options:
            \tprefix: <gold>[Bench @F@]<reset>
            \tstep: @F@

            """;

    private static final String FUNCTION = """
            function bench@F@_score@N@(p: player, n: number) :: number:
            \tset {_total} to 0
            \tloop {_n} times:
            \t\tadd loop-number * {@step} to {_total}
            \t\tif mod(loop-number, 3) = 0:
            \t\t\tremove 1 from {_total}
            \tif {_total} > 100:
            \t\tsend "{@prefix} %{_p}% scored %{_total}%" to {_p}
            \telse if {_total} > 10:
            \t\tsend "{@prefix} average score" to {_p}
            \telse:
            \t\tsend "{@prefix} low score" to {_p}
            \treturn {_total}

            """;

    private static final String EVENT = """
            on join:
            \tadd 1 to {bench@F@::%player's uuid%::joins@N@}
            \tif player has permission "bench.vip":
            \t\tsend "{@prefix} welcome back, VIP %player%" to player
            \tset {_score} to bench@F@_score@N@(player, 5)
            \tif {_score} is greater than 50:
            \t\tset {bench@F@::top::%player's uuid%} to {_score}

            on break of stone:
            \tplayer's gamemode is survival
            \tadd 1 to {bench@F@::%player's uuid%::broken@N@}
            \tif mod({bench@F@::%player's uuid%::broken@N@}, 100) = 0:
            \t\tsend "{@prefix} %{bench@F@::%player's uuid%::broken@N@}% blocks mined" to player

            """;

    private static final String COMMAND = """
            command /bench@F@x@N@ [<text>]:
            \tpermission: bench.use
            \ttrigger:
            \t\tif arg-1 is set:
            \t\t\tsend "{@prefix} you said %arg-1%" to sender
            \t\telse:
            \t\t\tloop {bench@F@::top::*}:
            \t\t\t\tsend "{@prefix} %loop-index%: %loop-value%" to sender

            """;

    /** Returns script contents keyed by path relative to Skript's scripts folder. */
    static Map<String, String> generate() {
        Map<String, String> scripts = new LinkedHashMap<>();
        for (int f = 0; f < FILES; f++) {
            StringBuilder script = new StringBuilder(fill(HEADER, f, 0));
            for (int n = 0; n < FUNCTIONS_PER_FILE; n++) {
                script.append(fill(FUNCTION, f, n));
            }
            for (int n = 0; n < EVENTS_PER_FILE; n++) {
                script.append(fill(EVENT, f, n));
            }
            for (int n = 0; n < COMMANDS_PER_FILE; n++) {
                script.append(fill(COMMAND, f, n));
            }
            scripts.put("bench/bench" + f + ".sk", script.toString());
        }
        return scripts;
    }

    /** One file's structure count: options, functions, two events per event block, and commands. */
    static int structuresPerFile() {
        return 1 + FUNCTIONS_PER_FILE + EVENTS_PER_FILE * 2 + COMMANDS_PER_FILE;
    }

    private static String fill(String template, int file, int n) {
        return template.replace("@F@", Integer.toString(file)).replace("@N@", Integer.toString(n));
    }

    private BenchmarkScripts() {}
}
